def put(value, name):
    key=name.upper().rstrip('.').lstrip('$')
    spec=FORMATS[key]
    def comparable(item):
        if item is None:return None
        if spec['character']:return str(item).rstrip()
        return Decimal(str(item))
    item=comparable(value)
    fallback=None
    for rule in spec['rules']:
        if rule['other']:
            fallback=rule['result'];continue
        if item in [comparable(v) for v in rule['values']]:return rule['result']
        for lo,hi in rule['ranges']:
            if item is not None and (str(lo).upper()=='LOW' or item>=comparable(lo)) and (str(hi).upper()=='HIGH' or item<=comparable(hi)):
                return rule['result']
    if fallback is not None:return fallback
    # No OTHER rule: SAS PUT falls back to the unformatted value.
    return '.' if value is None else str(value)

